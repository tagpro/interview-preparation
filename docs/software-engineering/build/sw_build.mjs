// Generate the site's service worker.
//
// The worker is generated rather than hand-written for one reason: its cache
// name has to change whenever any cached file changes, or a visitor keeps being
// served the old site forever. The name here is a hash of the contents of
// everything it precaches, so it cannot drift from what it is caching.
//
// The site is small and entirely static, so it precaches everything on install:
// one visit to the front page makes all seven deep dives readable offline, not
// just the pages that happened to be opened.
//
//     node sw_build.mjs <site-root>
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const SITE = path.resolve(process.argv[2] || '.');
const OUT = path.join(SITE, 'sw.js');

// Everything the site needs to render. Not the build directory, and not the
// worker itself -- the browser fetches that separately and by its own rules.
const KEEP = /\.(html|css|woff2|svg|png)$/;
function walk(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name < b.name ? -1 : 1)) {
    if (e.name === 'build' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (KEEP.test(e.name)) acc.push(p);
  }
  return acc;
}

const files = walk(SITE);
const rel = files.map(f => path.relative(SITE, f).split(path.sep).join('/'));

const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(path.relative(SITE, f)); hash.update(fs.readFileSync(f)); }
const VERSION = hash.digest('hex').slice(0, 12);
const bytes = files.reduce((n, f) => n + fs.statSync(f).size, 0);

const sw = `/* The site's offline cache. GENERATED by build/sw_build.mjs -- do not edit.
 *
 * The cache name is a hash of everything listed below, so publishing any change
 * to any of these files produces a new cache, and the old one is deleted on
 * activation. That is the whole update story: there is no manual versioning to
 * forget, and no way to serve a stale page from a previous deploy.
 */
const CACHE = 'ladder-${VERSION}';

const PRECACHE = [
  '.',
${rel.map(r => `  '${r}',`).join('\n')}
];

self.addEventListener('install', event => {
  // Take over as soon as this finishes rather than waiting for every tab of the
  // old version to close; the pages are static documents, so there is no
  // half-updated state to land in.
  self.skipWaiting();
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)));
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('ladder-') && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;   // leave anything external alone

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);

    // A request for a directory is a request for its index.
    const hit = await cache.match(req, { ignoreSearch: true })
      || (url.pathname.endsWith('/')
        ? await cache.match(url.pathname + 'index.html', { ignoreSearch: true })
        : undefined);
    if (hit) return hit;

    try {
      return await fetch(req);
    } catch (err) {
      // Offline, and not something we hold. A navigation gets the site's own
      // 404 page rather than the browser's error screen; anything else fails
      // as it would have anyway.
      if (req.mode === 'navigate') {
        const fallback = await cache.match(new URL('404.html', self.registration.scope).pathname);
        if (fallback) return fallback;
      }
      throw err;
    }
  })());
});
`;

fs.writeFileSync(OUT, sw);
console.log(`sw.js  cache ladder-${VERSION}  ${rel.length} files precached, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
for (const group of ['html', 'woff2', 'css', 'svg', 'png']) {
  const n = rel.filter(r => r.endsWith('.' + group)).length;
  if (n) console.log(`  ${String(n).padStart(2)} ${group}`);
}
